#!/usr/bin/env node
// Generates public/card-templates.js from lib/print/cards.mjs.
//
// lib/print/cards.mjs is the SINGLE source of truth (the server validates and
// prices against it). The browser can't import from lib/, and this repo has no
// build step, so the card data is emitted as a plain window global that card.html
// loads like /countries.js or /montage-music.js.
//
// Generated, never hand-edited — that's what keeps the storefront and the print
// bake from drifting apart. Re-run after ANY edit to cards.mjs:
//
//   node scripts/build-card-templates.mjs
//
// The check at the bottom of card.html fails loudly if the file is stale.

import { writeFileSync } from 'node:fs';
import * as cards from '../lib/print/cards.mjs';

const payload = {
  CARD_FORMATS: cards.CARD_FORMATS,
  OCCASIONS: cards.OCCASIONS,
  SECTIONS: cards.SECTIONS,
  OCCASION_GROUPS: cards.OCCASION_GROUPS,
  TEXT_ROLES: cards.TEXT_ROLES,
  FONTS: cards.FONTS,
  TYPE: cards.TYPE,
  FINISHES: cards.FINISHES,
  COLORWAYS: cards.COLORWAYS,
  DEFAULT_COLORWAY: cards.DEFAULT_COLORWAY,
  ORNAMENTS: cards.ORNAMENTS,
  CARD_TEMPLATES: cards.CARD_TEMPLATES,
  CARD_FAMILIES: cards.CARD_FAMILIES,
  GREETINGS: cards.GREETINGS,
  CARD_PACKS: cards.CARD_PACKS,
  DEFAULT_PACK: cards.DEFAULT_PACK,
};

const out = `// GENERATED by scripts/build-card-templates.mjs — DO NOT EDIT BY HAND.
// Source of truth: lib/print/cards.mjs. Re-run the script after changing it.
(function () {
  var C = ${JSON.stringify(payload, null, 2)};

  // Pure helpers mirrored from cards.mjs so the builder and the server agree.
  C.occasionById = function (id) {
    return C.OCCASIONS.filter(function (o) { return o.id === id; })[0] || null;
  };
  C.templateById = function (id) {
    return C.CARD_TEMPLATES.filter(function (t) { return t.id === id; })[0] || null;
  };
  C.templatesForOccasion = function (occasionId) {
    var occ = C.occasionById(occasionId);
    if (!occ) return [];
    return C.CARD_TEMPLATES.filter(function (t) {
      return occ.tags.every(function (tag) { return t.tags.indexOf(tag) !== -1; });
    });
  };
  C.occasionsWithCounts = function () {
    return C.OCCASIONS.map(function (o) {
      var fams = {};
      C.templatesForOccasion(o.id).forEach(function (t) { fams[t.family] = 1; });
      var c = Object.keys(fams).length;
      return Object.assign({}, o, { count: c });
    }).filter(function (o) { return o.count > 0; });
  };
  C.resolveText = function (template, values, greetingId) {
    values = values || {};
    greetingId = greetingId || 'holiday';
    return (template.text || []).map(function (z) {
      var dflt = (z.greet && z.greet[greetingId]) || z.default;
      var raw = Object.prototype.hasOwnProperty.call(values, z.id) ? values[z.id] : dflt;
      var role = C.TEXT_ROLES[z.role] || {};
      var max = role.maxChars || 120;
      return Object.assign({}, z, { default: dflt, value: String(raw == null ? '' : raw).slice(0, max) });
    });
  };
  C.familyTemplates = function (family) {
    return C.CARD_TEMPLATES.filter(function (t) { return t.family === family; });
  };
  C.cardTrimSize = function (formatId, orientation) {
    var f = C.CARD_FORMATS[formatId];
    if (!f) return null;
    var land = orientation === 'landscape';
    return { w: Math.round((land ? f.hIn : f.wIn) * f.dpi),
             h: Math.round((land ? f.wIn : f.hIn) * f.dpi), dpi: f.dpi };
  };
  C.cardBleedSize = function (formatId, orientation) {
    var f = C.CARD_FORMATS[formatId];
    if (!f) return null;
    var land = orientation === 'landscape';
    var wIn = land ? f.hIn : f.wIn, hIn = land ? f.wIn : f.hIn, b = f.bleedIn;
    return { w: Math.round((wIn + b * 2) * f.dpi), h: Math.round((hIn + b * 2) * f.dpi), dpi: f.dpi,
             offsetX: Math.round(b * f.dpi), offsetY: Math.round(b * f.dpi),
             bleedFracX: b / wIn, bleedFracY: b / hIn };
  };

  window.PopcodeCards = C;
})();
`;

const target = new URL('../public/card-templates.js', import.meta.url);
writeFileSync(target, out);
console.log(`Wrote public/card-templates.js — ${payload.CARD_TEMPLATES.length} templates, ${payload.OCCASIONS.length} occasions, ${out.length} bytes.`);
